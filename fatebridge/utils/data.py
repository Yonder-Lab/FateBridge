def get_hour_branch(hour: int) -> str:
    """Get the earthly branch for a given hour (0-23)."""
    # 传统时辰划分（每个时辰2小时）：
    # 子时: 23:00-01:00, 丑时: 01:00-03:00, 寅时: 03:00-05:00, 卯时: 05:00-07:00
    # 辰时: 07:00-09:00, 巳时: 09:00-11:00, 午时: 11:00-13:00, 未时: 13:00-15:00
    # 申时: 15:00-17:00, 酉时: 17:00-19:00, 戌时: 19:00-21:00, 亥时: 21:00-23:00
    if hour == 23 or hour == 0:
        return "子"
    elif hour == 1 or hour == 2:
        return "丑"
    elif hour == 3 or hour == 4:
        return "寅"
    elif hour == 5 or hour == 6:
        return "卯"
    elif hour == 7 or hour == 8:
        return "辰"
    elif hour == 9 or hour == 10:
        return "巳"
    elif hour == 11 or hour == 12:
        return "午"
    elif hour == 13 or hour == 14:
        return "未"
    elif hour == 15 or hour == 16:
        return "申"
    elif hour == 17 or hour == 18:
        return "酉"
    elif hour == 19 or hour == 20:
        return "戌"
    elif hour == 21 or hour == 22:
        return "亥"
    else:
        raise ValueError(f"Invalid hour: {hour}")  # 这种情况不应该出现



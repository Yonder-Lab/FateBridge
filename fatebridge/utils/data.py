def count_element_distribution(
    pillars: Mapping[str, Tuple[str, str]],
) -> Dict[Element, float]:
    """Weighted five-element tally over a pillar map.

    Standard 命局五行 weighting, identical across the career/health/wealth
    analyses it was extracted from: visible stem = 1.0, branch = 0.5, each
    hidden stem of the branch = 0.3. Returns a dict with every Element present
    (zero-initialised) so callers can index any element without a KeyError.
    """
    counts: Dict[Element, float] = {e: 0.0 for e in Element}
    for stem, branch in pillars.values():
        counts[STEM_ELEMENTS[stem][0]] += 1.0
        counts[BRANCH_ELEMENTS[branch][0]] += 0.5
        for hidden in BRANCH_HIDDEN_STEMS.get(branch, []):
            counts[STEM_ELEMENTS[hidden][0]] += 0.3
    return counts


# 十神 (Ten Gods) - relationships between day stem and other stems
class TenGod(Enum):
    COMPARE = "比肩"  # Same element, same polarity
    ROB_WEALTH = "劫财"  # Same element, different polarity
    FOOD_GOD = "食神"  # Generated by day stem, same polarity
    HURT_OFFICER = "伤官"  # Generated by day stem, different polarity
    POSITIVE_WEALTH = "正财"  # Destroyed by day stem, different polarity
    PARTIAL_WEALTH = "偏财"  # Destroyed by day stem, same polarity
    POSITIVE_OFFICER = "正官"  # Destroys day stem, different polarity
    SEVEN_KILLER = "七杀"  # Destroys day stem, same polarity
    POSITIVE_SEAL = "正印"  # Generates day stem, different polarity
    PARTIAL_SEAL = "偏印"  # Generates day stem, same polarity


def get_ten_god(day_stem: str, other_stem: str) -> TenGod:
    """Calculate the Ten God relationship between day stem and another stem."""
    day_element, day_polarity = STEM_ELEMENTS[day_stem]
    other_element, other_polarity = STEM_ELEMENTS[other_stem]

    if day_element == other_element:
        if day_polarity == other_polarity:
            return TenGod.COMPARE
        else:
            return TenGod.ROB_WEALTH
    elif GENERATION_CYCLE[day_element] == other_element:
        # Day stem generates other stem
        if day_polarity == other_polarity:
            return TenGod.FOOD_GOD
        else:
            return TenGod.HURT_OFFICER
    elif DESTRUCTION_CYCLE[day_element] == other_element:
        # Day stem destroys other stem
        if day_polarity == other_polarity:
            return TenGod.PARTIAL_WEALTH
        else:
            return TenGod.POSITIVE_WEALTH
    elif DESTRUCTION_CYCLE[other_element] == day_element:
        # Other stem destroys day stem
        if day_polarity == other_polarity:
            return TenGod.SEVEN_KILLER
        else:
            return TenGod.POSITIVE_OFFICER
    elif GENERATION_CYCLE[other_element] == day_element:
        # Other stem generates day stem
        if day_polarity == other_polarity:
            return TenGod.PARTIAL_SEAL
        else:
            return TenGod.POSITIVE_SEAL
    else:
        # This shouldn't happen with valid inputs
        raise ValueError(f"Invalid relationship between {day_stem} and {other_stem}")


